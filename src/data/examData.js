// Helper methods
export const getExamByOrgAndSlug = (orgSlug, postSlug) => {
  if (!orgSlug || !postSlug) return null;
  return SARKARI_EXAMS.find(
    e => e.orgSlug.toLowerCase() === orgSlug.toLowerCase() &&
         e.postSlug.toLowerCase() === postSlug.toLowerCase()
  );
};

export const getExamsByCategory = (category) => {
  return SARKARI_EXAMS.filter(e => e.category === category);
};

export const getExamsByOrg = (orgSlug) => {
  return SARKARI_EXAMS.filter(e => e.orgSlug.toLowerCase() === orgSlug.toLowerCase());
};
