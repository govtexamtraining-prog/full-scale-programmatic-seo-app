// Helper methods
export const getExamByOrgAndSlug = (orgSlug, postSlug) => {
  if (!orgSlug || !postSlug) return null;
  return SARKARI_EXAMS.find(
    e => e.orgSlug.toLowerCase() === orgSlug.toLowerCase() &&
         e.postSlug.toLowerCase() === postSlug.toLowerCase()
  );
};

export const getExamsByCategory = (category) => {
  if (!category || category === 'all') return SARKARI_EXAMS;
  return SARKARI_EXAMS.filter(e => e.category === category);
};

export const getExamsByOrg = (orgSlug) => {
  if (!orgSlug || orgSlug === 'all') return SARKARI_EXAMS;
  return SARKARI_EXAMS.filter(e => e.orgSlug.toLowerCase() === orgSlug.toLowerCase());
};

export const getExamsByState = (stateSlug) => {
  if (!stateSlug || stateSlug === 'all') return SARKARI_EXAMS;
  if (stateSlug === 'central') return SARKARI_EXAMS.filter(e => e.isCentral);
  return SARKARI_EXAMS.filter(e => e.stateSlug.toLowerCase() === stateSlug.toLowerCase());
};

export const getCentralExams = () => {
  return SARKARI_EXAMS.filter(e => e.isCentral);
};

export const getStateExams = () => {
  return SARKARI_EXAMS.filter(e => !e.isCentral);
};

export const getExamsByEducation = (level) => {
  if (!level || level === 'all') return SARKARI_EXAMS;
  return SARKARI_EXAMS.filter(e => e.educationLevel === level);
};
